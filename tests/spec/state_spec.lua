local mpv = require("support.mpv")

local A, B, C, D = "https://youtu.be/a", "https://youtu.be/b", "https://youtu.be/c", "https://youtu.be/d"

describe("merge_cmdline", function()
    it("splices new items at the resume slot so they play first", function()
        local pp = mpv.new():load()
        local items, new_count = pp.merge_cmdline({ A, B, C }, 1, { D })
        expect.eq(items, { A, D, B, C })
        expect.eq(new_count, 1)
    end)

    it("drops command-line items already in the saved list, ytdl:// form included", function()
        local pp = mpv.new():load()
        local items, new_count = pp.merge_cmdline({ A, B, C }, 1, { "ytdl://" .. B, D, D })
        expect.eq(items, { A, D, B, C })
        expect.eq(new_count, 1)
    end)

    it("returns the saved list untouched with no command-line items", function()
        local pp = mpv.new():load()
        local items, new_count = pp.merge_cmdline({ A, B }, 1, {})
        expect.eq(items, { A, B })
        expect.eq(new_count, 0)
    end)
end)

describe("read_saved_state", function()
    it("treats a truncated file as an empty playlist without raising", function()
        local h = mpv.new()
        local pp = h:load()
        h:write_state('{"items":["https://youtu.be/a","https://you')
        local state
        expect.no_error(function() state = pp.read_saved_state() end)
        expect.eq(state, { items = {}, current = 0 })
    end)

    it("returns an empty playlist when the file is missing", function()
        local pp = mpv.new():load()
        expect.eq(pp.read_saved_state(), { items = {}, current = 0 })
    end)

    it("dedupes saved items and keeps current pointing at the same video", function()
        local h = mpv.new()
        local pp = h:load()
        h:write_state(('{"items":[%q,%q,%q,%q],"current":3}'):format(A, B, A, C))
        expect.eq(pp.read_saved_state(), { items = { A, B, C }, current = 2 })
    end)

    it("clamps an out-of-range current", function()
        local h = mpv.new()
        local pp = h:load()
        h:write_state(('{"items":[%q,%q],"current":9}'):format(A, B))
        expect.eq(pp.read_saved_state().current, 1)
        h:write_state(('{"items":[%q,%q],"current":-4}'):format(A, B))
        expect.eq(pp.read_saved_state().current, 0)
    end)
end)

describe("save_saved_state", function()
    it("round-trips through read_saved_state and leaves no temp file", function()
        local h = mpv.new()
        local pp = h:load()
        pp.save_saved_state({ A, B }, 1)
        expect.eq(pp.read_saved_state(), { items = { A, B }, current = 1 })
        expect.falsy(h:file_exists(h:state_file() .. ".tmp"))
    end)

    it("creates the state directory on first save", function()
        local h = mpv.new()
        local pp = h:load()
        expect.falsy(h:file_exists(h:state_file()))
        pp.save_saved_state({ A }, 0)
        expect.truthy(h:read_state())
    end)

    it("removes the file when the playlist is empty", function()
        local h = mpv.new()
        local pp = h:load()
        pp.save_saved_state({ A }, 0)
        pp.save_saved_state({}, 0)
        expect.is_nil(h:read_state())
    end)
end)
